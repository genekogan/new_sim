#!/usr/bin/env node
// Lane S3 (2026-10-20), split per piece by lane SCORE (2026-10-22): builds the world's music playlist
// (apps/web/src/score/playlist/) from the vendored Sim Score (vendor/sim-score, refreshed by sync-sim-score.mjs).
//
// - playlist/engine.mjs: the nine engine files (theory, compose, instruments, more-instruments, conductor, then the
//   optional phrasing, spc, dialogue, groove, in sim-score's index.html order) unchanged inside createPlaylistScore(Tone),
//   which takes Tone explicitly and keeps `Sim` private (each engine IIFE root `typeof window ... globalThis` becomes
//   that private scope); PLAYLIST; loadPiece(id), one dynamic import per piece so the bundler gives each its own chunk.
// - playlist/pieces/<id>.mjs: the piece file unchanged inside `export default function register(Sim, Tone)`.
// - playlist/BUILD.json: source commit, playlist, sha256 of every generated file (playlist.test.ts rebuilds and compares).
// Nothing plays on import. Edit PLAYLIST below to change the playlist, then rerun:
//
//   node tools/score/build-playlist.mjs
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const vendor = resolve(root, 'vendor/sim-score');
export const OUT = resolve(root, 'apps/web/src/score/playlist');

// The playlist, in play order (README.md "World playlist"): sim-score's round-four "New pieces" family in catalog order,
// then the twelve round-three pieces lane S3 chose for Gene's named influences.
export const PLAYLIST = [
  'skylight-rain', 'harbour-mouth', 'branch-line', 'lantern-square', 'nightside-pass', 'hydroponics-deck', 'section-lines',
  'citronella', 'heron-causeway', 'second-ring-road', 'sunken-causeway', 'cheese-stall', 'firn-light', 'aerial-causeway',
  'service-corridor', 'after-the-fireworks', 'night-approach', 'headland', 'evening-rounds', 'velour', 'halogen',
  'cloud-street', 'lamplighter', 'frost-fair', 'heat-lightning', 'under-glass', 'flying-junction', 'coin-laundry',
  'pixel-town', 'downtown-rush', 'neon-shibuya', 'departure-lounge', 'line-clear', 'mirror-ball',
  'night-drive', 'plaza-mall', 'grand-prix', 'magic-orbit', 'montage', 'night-patrol',
];
export const ENGINE = ['theory', 'compose', 'instruments', 'more-instruments', 'conductor', 'phrasing', 'spc', 'dialogue', 'groove'];
const ROOT = '(typeof window !== "undefined" ? window : globalThis)';
const HEAD = '/* eslint-disable */\n// @ts-nocheck\n';
const sha256 = (s) => createHash('sha256').update(s).digest('hex');

/** The generated files (path relative to playlist/ -> text). With write, writes them and removes chunks of dropped pieces. */
export function buildPlaylist({ write = false, log = () => {} } = {}) {
  const prov = JSON.parse(readFileSync(join(vendor, 'PROVENANCE.json'), 'utf8'));
  const commit = prov.source.commit, short = commit.slice(0, 7);
  const read = (p) => readFileSync(join(vendor, p), 'utf8');
  const roots = (text) => text.split(ROOT).length - 1;
  if (new Set(PLAYLIST).size !== PLAYLIST.length) throw Error('PLAYLIST lists a piece twice');
  const files = new Map();

  const engine = ENGINE.map((m) => {
    const path = `site/engine/${m}.js`, text = read(path);
    if (roots(text) !== 1) throw Error(`${path}: expected one root expression, found ${roots(text)}`);
    return `// Source: vendor/sim-score/${path}\n${text.replace(ROOT, '(scope)').trimEnd()}\n`;
  });
  files.set('engine.mjs', `// Generated by tools/score/build-playlist.mjs from vendor/sim-score (sim-score ${short}); do not edit. See BUILD.json.
// Sim Score's engine inside a private scope with Tone passed in, the playlist, and one lazy chunk per piece.
// Nothing plays on import; the player (gen-mesh/music.ts) builds a Conductor, fetches a piece's chunk just before it plays
// and registers it with register(Sim, Tone).
${HEAD}export const PLAYLIST = ${JSON.stringify(PLAYLIST)};
const PIECES = {
${PLAYLIST.map((id) => `  ${JSON.stringify(id)}: () => import(${JSON.stringify(`./pieces/${id}.mjs`)}),`).join('\n')}
};
/** The module of a playlist piece (its own chunk); its default export registers the piece: register(Sim, Tone). */
export const loadPiece = (id) => (PIECES[id] ?? (() => Promise.reject(Error(\`not on the playlist: \${id}\`))))();
export function createPlaylistScore(Tone) {
  const scope = { Sim: {} };
  const Sim = scope.Sim;

${engine.join('\n')}
  return Sim;
}
`);
  for (const id of PLAYLIST) {
    const path = `site/pieces/${id}.js`;
    if (!existsSync(join(vendor, path))) throw Error(`${id} is on the playlist but vendor/sim-score has no ${path}`);
    const text = read(path);
    if (roots(text) !== 0) throw Error(`${path}: a piece should not have a root expression`);
    files.set(`pieces/${id}.mjs`, `// Generated by tools/score/build-playlist.mjs from vendor/sim-score/${path} (sim-score ${short}); do not edit.
${HEAD}export default function register(Sim, Tone) {
${text.trimEnd()}
}
`);
  }
  const outputs = Object.fromEntries([...files].map(([p, t]) => [p, sha256(t)]));
  files.set('BUILD.json', JSON.stringify({
    generator: 'tools/score/build-playlist.mjs', source: { vendored: 'vendor/sim-score', commit },
    tone: '15.1.22', engine: ENGINE, playlist: PLAYLIST, outputs,
  }, null, 2) + '\n');

  // pieces in the catalog's round-four family that the playlist leaves out (sync tells you when sim-score adds one)
  const sandbox = {}; sandbox.globalThis = sandbox;
  vm.runInNewContext(read('site/catalog.js'), sandbox);
  const fresh = sandbox.Sim?.catalog?.families?.find(([name]) => name === 'New pieces')?.[1] ?? [];
  const left = fresh.filter((id) => !PLAYLIST.includes(id));

  if (write) {
    mkdirSync(join(OUT, 'pieces'), { recursive: true });
    for (const [p, t] of files) writeFileSync(join(OUT, p), t);
    for (const f of readdirSync(join(OUT, 'pieces'))) if (!files.has(`pieces/${f}`)) {
      rmSync(join(OUT, 'pieces', f)); log(`  removed pieces/${f} (no longer on the playlist)`);
    }
    const kb = (t) => `${(t.length / 1024).toFixed(0)} KB`;
    const biggest = [...files].filter(([p]) => p.startsWith('pieces/')).sort((a, b) => b[1].length - a[1].length)[0];
    log(`playlist (sim-score ${short}): ${PLAYLIST.length} pieces; engine.mjs ${kb(files.get('engine.mjs'))}, largest piece ${biggest[0]} ${kb(biggest[1])} (source, before minifying)`);
    if (left.length) log(`  catalog "New pieces" not on the playlist: ${left.join(', ')}`);
  }
  return { files, commit, left };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) buildPlaylist({ write: true, log: console.log });
