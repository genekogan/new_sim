#!/usr/bin/env node
// Lane S3 (2026-10-20): builds apps/web/src/score/playlist-runtime.mjs, the world's music playlist, from Gene's Sim Score
// repository (Tone.js pieces composed in the browser, no samples). The engine files and the chosen pieces are copied
// unchanged inside one function that takes Tone explicitly and keeps `Sim` private; the five engine IIFE roots
// (`typeof window !== "undefined" ? window : globalThis`) become that private scope. Nothing plays on import.
//
//   node tools/score/import-playlist.mjs [<sim-score-repo>]
// Writes playlist-runtime.mjs and PLAYLIST-PROVENANCE.json (source revision, per-file sha256) next to runtime.mjs.
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const src = resolve(process.argv[2] ?? '<sim-score-repo>');
const outDir = resolve(root, 'apps/web/src/score');
const REVISION = '3b806f2084d5dcefcf9a2282828765657bd74220';

// The playlist, in play order (see apps/web/src/score/README.md "World playlist" for why these).
export const PLAYLIST = [
  'pixel-town', 'downtown-rush', 'neon-shibuya', 'departure-lounge', 'line-clear', 'mirror-ball',
  'night-drive', 'plaza-mall', 'grand-prix', 'magic-orbit', 'montage', 'night-patrol',
];
const ENGINE = ['theory', 'compose', 'instruments', 'more-instruments', 'conductor'];
const ROOT = '(typeof window !== "undefined" ? window : globalThis)';

const head = execFileSync('git', ['-C', src, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
if (head !== REVISION) throw new Error(`sim-score HEAD ${head} is not the reviewed ${REVISION}`);
const dirty = execFileSync('git', ['-C', src, 'status', '--porcelain', '--', 'site/engine', 'site/pieces'], { encoding: 'utf8' }).trim();
if (dirty) throw new Error(`sim-score has local changes under site/: ${dirty}`);

const sha = (s) => createHash('sha256').update(s).digest('hex');
const files = [], parts = [];
for (const [path, isEngine] of [...ENGINE.map((f) => [`site/engine/${f}.js`, true]), ...PLAYLIST.map((p) => [`site/pieces/${p}.js`, false])]) {
  const text = readFileSync(resolve(src, path), 'utf8');
  const roots = text.split(ROOT).length - 1;
  if (isEngine && roots !== 1) throw new Error(`${path}: expected one root expression, found ${roots}`);
  if (!isEngine && roots !== 0) throw new Error(`${path}: a piece should not have a root expression`);
  const body = isEngine ? text.replace(ROOT, '(scope)') : text;
  files.push({ path, sha256: sha(text), rootReplacements: roots });
  parts.push(`// Source: ${path}\n${body.trimEnd()}\n`);
}

const out = `// Generated by tools/score/import-playlist.mjs from Sim Score ${REVISION.slice(0, 7)}; see PLAYLIST-PROVENANCE.json.
// The world's music playlist: Sim Score's engine plus ${PLAYLIST.length} pieces, unchanged inside a private scope with Tone passed in.
// Nothing plays on import; the player (gen-mesh/music.ts) builds a Conductor and plays pieces in PLAYLIST order.
/* eslint-disable */
// @ts-nocheck
export const PLAYLIST = ${JSON.stringify(PLAYLIST)};
export function createPlaylistScore(Tone) {
  const scope = { Sim: {} };
  const Sim = scope.Sim;

${parts.join('\n')}
  return Sim;
}
`;
writeFileSync(resolve(outDir, 'playlist-runtime.mjs'), out);
writeFileSync(resolve(outDir, 'PLAYLIST-PROVENANCE.json'), JSON.stringify({
  sourceRepository: '<sim-score-repo>', sourceRevision: REVISION,
  status: 'world playlist (lane S3, 2026-10-20); see README.md "World playlist"', tone: '15.1.22',
  transformation: 'Engine and piece files concatenated unchanged inside createPlaylistScore(Tone); five engine root expressions replaced with the private scope.',
  playlist: PLAYLIST, files, outputSha256: sha(out),
}, null, 2) + '\n');
console.log(`playlist-runtime.mjs: ${PLAYLIST.length} pieces, ${(out.length / 1024).toFixed(0)} KB`);
