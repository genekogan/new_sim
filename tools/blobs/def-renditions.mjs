#!/usr/bin/env node
// Lane W3b (2026-10-19): smaller wire encodings ("renditions") of core mesh assets, served by /assets/<source sha>.glb
// in place of the source (apps/server/src/god/asset-wire.ts). Defs, def hashes and worlds are untouched.
//   node tools/blobs/def-renditions.mjs <snapshot.json | sha,sha,...> [--jobs 6] [--min-gain 0.1] [--work <dir>] [--dry]
// For each mesh asset (a world snapshot's defs, or a list of shas) that is a core asset (worlds/core-assets/*index.json),
// tools/blobs/campus-parts.mjs --nohide re-encodes it with a 1 m design distance (--texels 2600 --err/--step 0.125 mm:
// stricter than the campus's 2 m, since a Soul's eye or a walking camera can come that close). A rendition is kept only
// when its brotli-11 bytes are at least --min-gain smaller than the source's and every named node of the source is still
// there (the viewer finds `roof` by name). Kept files: worlds/core-assets/renditions/<sha>.glb + renditions.json.
// Look check (separate, real Chrome): team/scratch/t4/w3b/item2/look-defs.mjs paired renders source vs rendition.
import { execFile } from 'node:child_process';
import { createHash } from 'node:crypto';
import { copyFileSync, existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { brotliCompressSync, constants as Z } from 'node:zlib';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const CORE = join(ROOT, 'worlds/core-assets'), OUT = join(CORE, 'renditions'), INDEX = join(CORE, 'renditions.json');
const argv = process.argv.slice(2), opt = (k, d) => { const i = argv.indexOf(k); return i < 0 ? d : argv[i + 1]; };
const JOBS = +opt('--jobs', 6), MIN_GAIN = +opt('--min-gain', 0.1), WORK = resolve(opt('--work', join(ROOT, '.renditions-work'))), DRY = argv.includes('--dry');
export const OPTIONS = ['--nohide', '--texels', '2600', '--err', '0.000125', '--step', '0.000125'];
const sha256 = (b) => createHash('sha256').update(b).digest('hex');
const br = (b) => brotliCompressSync(b, { params: { [Z.BROTLI_PARAM_QUALITY]: 11, [Z.BROTLI_PARAM_SIZE_HINT]: b.length } }).length;
const names = (glb) => { const n = glb.readUInt32LE(12), j = JSON.parse(glb.subarray(20, 20 + n).toString('utf8')); return new Set((j.nodes ?? []).map((x) => x.name).filter(Boolean)); };

const core = {}; for (const f of readdirSync(CORE).filter((n) => n.endsWith('index.json'))) Object.assign(core, JSON.parse(readFileSync(join(CORE, f), 'utf8')).assets);
const input = argv[0]; if (!input) { console.error('usage: def-renditions.mjs <snapshot.json | sha,sha,...>'); process.exit(2); }
const shas = existsSync(input) ? [...new Set(JSON.parse(readFileSync(input, 'utf8')).defs.filter((d) => d.make?.kind === 'mesh').map((d) => d.make.asset))] : input.split(',');
const index = existsSync(INDEX) ? JSON.parse(readFileSync(INDEX, 'utf8')) : { schema: 'core-renditions/1', renditions: {} };
index.note = 'Smaller wire encodings of core mesh assets, served by GET /assets/<source sha>.glb in their place. Generated by tools/blobs/def-renditions.mjs; do not edit.';
index.options = OPTIONS.join(' ');
mkdirSync(WORK, { recursive: true }); if (!DRY) mkdirSync(OUT, { recursive: true });
const todo = shas.filter((s) => core[s]?.ext === 'glb' && !core[s].animations?.length);
console.log(`${shas.length} mesh assets, ${todo.length} static core GLBs`);
const rows = []; let next = 0;
const run = (sha) => new Promise((ok) => {
  const src = join(ROOT, core[sha].path), out = join(WORK, `${sha}.glb`);
  execFile(process.execPath, [join(ROOT, 'tools/blobs/campus-parts.mjs'), src, out, ...OPTIONS], { maxBuffer: 64 << 20 }, (err) => {
    if (err || !existsSync(out)) { rows.push({ sha, path: core[sha].path, kept: false, why: `failed: ${String(err?.message ?? 'no output').split('\n')[0]}` }); return ok(); }
    const a = readFileSync(src), b = readFileSync(out), aBr = br(a), bBr = br(b), lost = [...names(a)].filter((x) => !names(b).has(x) && /^(body|roof)$/.test(x));
    const gain = 1 - bBr / aBr, kept = gain >= MIN_GAIN && !lost.length, rsha = sha256(b);
    rows.push({ sha, path: core[sha].path, bytes: a.length, br: aBr, renditionBytes: b.length, renditionBr: bBr, gain: +gain.toFixed(3), kept, ...(lost.length ? { why: `lost nodes ${lost}` } : !kept ? { why: 'gain below --min-gain' } : {}) });
    if (kept && !DRY) { const rel = `worlds/core-assets/renditions/${rsha}.glb`; copyFileSync(out, join(ROOT, rel)); index.renditions[sha] = { sha: rsha, path: rel, bytes: b.length, source: core[sha].path }; }
    ok();
  });
});
await Promise.all(Array.from({ length: JOBS }, async () => { while (next < todo.length) await run(todo[next++]); }));
rows.sort((x, y) => (y.br ?? 0) - (x.br ?? 0));
const sum = (k, f = () => true) => rows.filter(f).reduce((n, r) => n + (r[k] ?? 0), 0);
const report = { assets: rows.length, kept: rows.filter((r) => r.kept).length, br: sum('br'), wireBr: sum('br', (r) => !r.kept) + sum('renditionBr', (r) => r.kept), rows };
if (!DRY) { index.renditions = Object.fromEntries(Object.entries(index.renditions).sort(([a], [b]) => (a < b ? -1 : 1))); writeFileSync(INDEX, JSON.stringify(index, null, 1) + '\n'); }
writeFileSync(join(WORK, 'report.json'), JSON.stringify(report, null, 1));
console.log(JSON.stringify({ assets: report.assets, kept: report.kept, br: report.br, wireBr: report.wireBr }));
