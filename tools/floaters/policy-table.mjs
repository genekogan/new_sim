#!/usr/bin/env node
// Writes tools/floaters/POLICY.md: the floater verdict for every verb of the Mars registry, generated
// from engine/bodies/policy.ts (the registry is enumerated read-only; nothing is changed).
// Needs the viewer's runtime deps (zod) resolvable from mars/viewer.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ENGINE = path.resolve(HERE, '..', '..', 'mars', 'viewer', 'engine');
const { createRegistry } = await import(path.join(ENGINE, 'api', 'registry.ts'));
const { SEQUENCE_VERBS } = await import(path.join(ENGINE, 'sequence', 'runner.ts'));
const { policyRows, FLOATER_POLICY, R } = await import(path.join(ENGINE, 'bodies', 'policy.ts'));

const verbs = [...createRegistry().keys(), ...Object.keys(SEQUENCE_VERBS)];
const missing = verbs.filter((v) => !FLOATER_POLICY[v]);
const extra = Object.keys(FLOATER_POLICY).filter((v) => !verbs.includes(v));
if (missing.length || extra.length) throw new Error(`policy out of date: missing ${missing.join(', ') || '—'}; extra ${extra.join(', ') || '—'}`);
const rows = policyRows(verbs);
const count = (s) => rows.filter((r) => r.status === s).length;
const esc = (s) => s.replace(/\|/g, '\\|');
const md = [
  '# Floater policy — every Mars verb',
  '',
  'Generated by `tools/floaters/policy-table.mjs` from `mars/viewer/engine/bodies/policy.ts`; do not edit by hand.',
  `${verbs.length} verbs (${verbs.length - Object.keys(SEQUENCE_VERBS).length} registry + ${Object.keys(SEQUENCE_VERBS).length} sequence built-ins): **${count('works')} works, ${count('approximates')} approximates, ${count('refuses')} refuses**.`,
  '',
  'A floater is a static scanned head: no hands, arms, feet or lap. *works* = the verb keeps its meaning;',
  '*approximates* = ordinary engine semantics on the ground pose, drawn hovering (named); *refuses* = never faked.',
  'Use `admitFloaters(verb, params, bodyOf)` for the role-aware verdict of a concrete call.',
  '',
  '## Reasons',
  '',
  ...Object.entries(R).map(([k, v]) => `- \`${v}\` (${k})`),
  '- `floater.not-involved` — no floater among the params; ordinary validation applies',
  '- `floater.unknown-verb` — a verb with no policy entry (refused when a floater is named)',
  '- `floater.via-alternatives` — living_intention: every objective has an admissible alternative',
  '',
  '## Table',
  '',
  '| verb | verdict | reason | note | roles / delegation |',
  '|---|---|---|---|---|',
  ...rows.map((r) => `| \`${r.verb}\` | ${r.status} | \`${r.reason}\` | ${esc(r.note)} | ${esc(r.roles)} |`),
  '',
];
fs.writeFileSync(path.join(HERE, 'POLICY.md'), md.join('\n'));
console.log(`POLICY.md: ${verbs.length} verbs — ${count('works')} works, ${count('approximates')} approximates, ${count('refuses')} refuses`);
