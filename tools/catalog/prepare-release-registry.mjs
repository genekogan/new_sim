// Build a fresh registry from committed source and a real exact-hash render/PM review.
import assert from 'node:assert/strict';
import {readFileSync, mkdirSync, writeFileSync, existsSync} from 'node:fs';
import {resolve,join} from 'node:path';
import {createHash} from 'node:crypto';
import {execFileSync} from 'node:child_process';
import {Registry,buildCoreItems,writeCore,pinReleaseSeed,buildItem,publishItem,applyReviews,promoteChecked} from '../../packages/catalog/src/index.ts';
import {generateReviewQueue} from './review-queue.mjs';
const [outArg,receiptArg,approvalArg]=process.argv.slice(2), out=resolve(outArg), receiptFile=resolve(receiptArg);
if(existsSync(out))throw Error('output must be a fresh directory');
const receiptBytes=readFileSync(receiptFile), receipt=JSON.parse(receiptBytes), approval=JSON.parse(readFileSync(approvalArg));
const receiptHash=createHash('sha256').update(receiptBytes).digest('hex');
assert.equal(receiptHash,approval.renderReportSHA256,'review must name the actual inspected receipt');
assert.equal(approval.verdict,'ok'); assert.ok(approval.by.startsWith('pm:')||approval.by.startsWith('human:'));
mkdirSync(out,{recursive:true});
const source=execFileSync('git',['rev-parse','HEAD'],{encoding:'utf8'}).trim(), registry=new Registry(join(out,'registry'));
const {items,rows}=await buildCoreItems({run:'release-seed-'+source});
writeCore(registry,items,'release-seed-'+source);
const seedPinning=pinReleaseSeed(registry,'release-seed-pin-'+source);
const intents=JSON.parse(readFileSync(new URL('../../packages/catalog/eval/intents.json',import.meta.url))).intents;
const built=await buildItem(resolve('packages/catalog/items/object-tool/rain-gauge'),registry,{run:'release-item-'+source,receipt,intents});
assert.equal(built.item.id,approval.id);assert.equal(built.entry.def1Hash,approval.def1Hash);
assert.ok(built.ok,JSON.stringify(built.gates));
const candidate=publishItem(registry,built,'release-candidate-'+source);
generateReviewQueue(registry,receipt,receiptFile,join(out,'review'));
const entry=registry.resolve(built.item.id+'@'+built.item.major,'candidate');
applyReviews(registry,[{id:entry.id,major:entry.major,rev:entry.rev,itemHash:entry.itemHash,verdict:approval.verdict,note:approval.note}],approval.by,'release-review-'+source);
const stable=promoteChecked(registry,[entry.id],'release-stable-'+source);
const report={source,receiptHash,review:approval,seedCount:items.length,seedPinning:{stable:seedPinning.stable,candidate:seedPinning.candidate,changed:seedPinning.changed},seedGates:Object.fromEntries(['G1','G2','G3'].map(g=>[g,rows.filter(r=>r.gates.some(o=>o.gate===g&&!o.ok)).length])),candidate:candidate.seq,stable,item:built.entry,registry:join(out,'registry'),limits:'Seed items remain grandfathered; initial G4 baseline approval holds are retained. Automatic promotion remains blocked without G7.'};
writeFileSync(join(out,'PREPARED.json'),JSON.stringify(report,null,2)+'\n');console.log(JSON.stringify(report));
