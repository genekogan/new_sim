import { test } from 'node:test';
import assert from 'node:assert/strict';
import { Hono } from 'hono';
import { coreRef } from '@sim/world-compiler';
import { Db } from '../db.ts';
import { ApiError } from '../souls.ts';
import { GodMode, type WorldBuildMessage, type WorldDiffMessage } from './god.ts';
import { mountGodRoutes } from './routes.ts';
import { holder } from '../../../../tools/god-skill/lib/locks.mjs';

test('R1/E1: chapter adoption, private asks, covenant and site reports coexist with holder liveness and doctor', async t => {
  const db = new Db(':memory:'); t.after(() => db.close());
  const emitted: (WorldBuildMessage | WorldDiffMessage)[] = [];
  const god = new GodMode(db, { worldId: 'integrity-locks', ownerId: 'owner', tick: () => 1, emit: m => emitted.push(m) });
  const token = god.mintFor({ id: 'owner', role: 'user' }, 'lead');
  const app = new Hono();
  mountGodRoutes(app, { god, worldName: 'integration', requireUser: async () => { throw Error('unused'); }, soulFromBearer: () => null, baseOf: () => 'http://127.0.0.1:5365', limitIp: () => {} });
  app.onError((e, c) => e instanceof ApiError ? c.json({ code: e.code }, e.status as 400) : c.json({ error: String(e) }, 500));
  let identity = holder('integration command');
  const req = async (path: string, body?: unknown) => {
    const response = await app.request(path, { method: body === undefined ? 'GET' : 'POST', headers: { authorization: `Bearer ${token}`, 'content-type': 'application/json', 'x-eden-god-holder': JSON.stringify(identity) }, ...(body === undefined ? {} : { body: JSON.stringify(body) }) });
    assert.equal(response.status, 200); assert.equal(response.headers.get('cache-control'), 'no-store');
    return response.json();
  };
  const place = (name: string, x: number) => ({ op: 'place', def: coreRef('bench'), name, p: [x, 0] });
  assert.equal(god.act({ ops: [place('included', 30), place('preserved', 40)] }).accepted, true);
  const input = { title: 'Private chapel', steps: ['shell'], site: { at: [0, 0], size: [20, 20] }, brief: 'Private green spires', asks: ['Private quiet entrance'], include: ['included'] };
  const first = await req('/v1/god/builds', { ...input, id: 'chapel' });
  assert.equal(first.ok, true); assert.equal(first.report.ground.samples, 289);
  assert.deepEqual(first.build.lead.holder, identity); assert.equal(first.build.lead.live, true);
  const build = { id: 'chapel', lease: first.lease };
  const refused = await req('/v1/god/act', { ops: [{ op: 'set', id: 'preserved', name: 'stolen' }], build });
  assert.equal(refused.failures[0].code, 'build.outside');
  assert.equal((await req('/v1/god/act', { ops: [place('chapter-root', 0)], build })).accepted, true);
  assert.equal((await req('/v1/god/act', { ops: [{ op: 'set', id: 'included', name: 'included-renamed' }], build })).accepted, true);
  const done = await req('/v1/god/builds/chapel/done', {});
  assert.equal(done.ok, true); assert.equal(done.receipt.refused.count, 1); assert.equal(done.receipt.openAsks, 1);
  assert.equal(done.receipt.undoability.ok, true);
  const root = god.model.get('chapter-root')!.id;
  identity = { ...identity, start: 'previous process incarnation' };
  const chapter = await req('/v1/god/builds', { ...input, id: 'chapel-2', root: 'chapel', include: ['included-renamed'], brief: 'Private copper roof' });
  assert.equal(chapter.ok, true); assert.equal(chapter.report.ground.samples, 289);
  assert.equal(chapter.build.root, 'chapel'); assert.equal(chapter.build.chapterOf, 'chapel');
  assert.deepEqual(chapter.build.roots.map((r: { id: string }) => r.id), [root]);
  assert.deepEqual(chapter.build.initialRoots, [root]);
  assert.deepEqual(chapter.build.include, [god.model.get('included-renamed')!.id]);
  assert.deepEqual(chapter.build.chapters, [{ id: 'chapel', brief: input.brief, asks: input.asks }]);
  assert.deepEqual(chapter.build.plan.asks, input.asks);
  assert.deepEqual(chapter.build.lead.holder, identity); assert.equal(chapter.build.lead.live, false);
  const doctor = await req('/v1/god/doctor');
  assert.equal(doctor.locks.find((l: { id: string }) => l.id === 'chapel-2').stale, true);
  assert.equal((await req('/v1/god/doctor', { fix: true })).locks.find((l: { id: string }) => l.id === 'chapel-2').fixed, true);
  const retained = (await req('/v1/god/builds/chapel-2')).build;
  assert.equal(retained.paused.explicit, true); assert.deepEqual(retained.chapters, chapter.build.chapters);
  assert.deepEqual(retained.initialRoots, [root]);
  const publicData = JSON.stringify([god.publicSnapshot(), god.builds.publicList(), emitted]);
  for (const privateValue of ['Private green spires', 'Private quiet entrance', 'Private copper roof', identity.start, 'chapterOf', 'refusalCount']) assert.equal(publicData.includes(privateValue), false, privateValue);
});
