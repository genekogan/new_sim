// Focused isolated fake-world proof using the repository's existing Playwright
// dependency/cache convention. Boot fresh Eden on Game's assigned ports first.
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { steerReceipt } from '../src/steer-receipt.ts';
const root = fileURLToPath(new URL('../../../', import.meta.url));
const base = process.env.SIM_GAME_TEST_BASE ?? 'http://127.0.0.1:4960';
assert.match(new URL(base).hostname, /^(127\.0\.0\.1|localhost)$/);
assert.ok(Number(new URL(base).port) >= 4960 && Number(new URL(base).port) <= 4969);
process.env.PLAYWRIGHT_BROWSERS_PATH ??= root + '.e2e/browsers';
const require = createRequire(new URL('../../../mars/viewer/package.json', import.meta.url));
const { chromium } = require('@playwright/test');
const config = await (await fetch(base + '/w/eden/v1/config')).json();
assert.equal(config.devAuth, true, 'This proof requires isolated local DEV_AUTH');
const output = root + '.e2e/runs/human-frame-' + new Date().toISOString().replaceAll(':', '-');
mkdirSync(output, { recursive: true });
const browser = await chromium.launch({ headless: true, args: ['--enable-unsafe-swiftshader'] });
const checks = [], errors = [];
let page;
const check = (name, value) => { assert.ok(value, name); checks.push({ name, pass: true }); };
try {
  const spectator = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  page = await spectator.newPage(); page.on('pageerror', error => errors.push(error.message));
  const privateReads = [];
  page.on('request', request => { if (/\/v1\/souls\//.test(request.url())) privateReads.push(new URL(request.url()).pathname); });
  await page.goto(base + '/');
  check('Eden is first entry; Toy removed only from navigation', await page.locator('.world-cards a').first().getAttribute('href') === '/w/eden' && await page.locator('a[href="/w/toy"]').count() === 0);
  await page.goto(base + '/w/eden');
  // UI2: the Soul panel is hidden on arrival and opens from a name plate.
  const plate = page.locator('.world-canvas-host [data-soul-id]').filter({ hasText: 'Eden' }).first();
  await page.waitForFunction(() => [...document.querySelectorAll('.world-canvas-host [data-soul-id]')].some(el => el.style.visibility !== 'hidden' && el.getBoundingClientRect().width > 0));
  check('Soul panel hidden on arrival', await page.locator('#soul-panel').isHidden());
  await plate.click({ force: true });
  await page.locator('#soul-panel .soul-card').waitFor();
  check('Selection moves accessible focus to the Soul heading', await page.locator('.human-panel h1').evaluate(el => el === document.activeElement));
  check('Spectator selection exposes no owner form or private dashboard request', await page.locator('#soul-direction').count() === 0 && privateReads.length === 0);
  const canvas = await page.locator('canvas[aria-label="Live 3D view of the world"]').elementHandle();
  check('Viewer exists', !!canvas);
  await page.getByRole('button', { name: 'Close panel', exact: true }).click();
  await page.locator('#soul-panel').waitFor({ state: 'hidden' });
  await plate.click({ force: true });await page.locator('#soul-panel .soul-card').waitFor();
  check('Panel close and reopen keep original viewer mounted', await page.evaluate(el => el === document.querySelector('canvas'), canvas));
  await page.screenshot({ path: output + '/spectator-desktop.png' });
  writeFileSync(output + '/spectator.yml', await page.locator('body').ariaSnapshot());
  await spectator.close();

  const owner = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  await owner.addInitScript(() => { localStorage.setItem('sim.dev', 'admin'); localStorage.setItem('sim.authUi', '1'); });
  page = await owner.newPage(); page.on('pageerror', error => errors.push(error.message));
  await page.goto(base + '/w/eden');
  await page.getByRole('button', { name: 'Your Soul', exact: true }).click();
  const direction = page.locator('#soul-direction');
  await direction.waitFor();
  await direction.fill('rest');
  await page.getByRole('button', { name: 'Send direction', exact: true }).click();
  await page.getByText('Rule accepted', { exact: true }).waitFor();
  check('Actual HTTP mandate acceptance is never completed action', await page.getByText('Saved as direction. Completion has not been confirmed.', { exact: true }).isVisible());
  check('Accepted draft clears', await direction.inputValue() === '');
  const me = await (await owner.request.get(base + '/w/eden/v1/me', { headers: { authorization: 'Bearer dev:admin' } })).json();
  const privatePath = base + `/w/eden/v1/souls/${me.souls[0].id}`;
  const exact = await owner.request.post(privatePath + '/intent', { headers: { authorization: 'Bearer dev:admin' }, data: { intent: { goal: 'rest', target: null } } });
  const exactBody = await exact.json();
  check('Actual exact-intent HTTP response is consumed with canonical top-level event ID', exact.status() === 200 && steerReceipt(exact.status(), exactBody, 'intent').kind === 'accepted' && steerReceipt(exact.status(), exactBody, 'intent').seq === exactBody.seq);
  check('Owner dashboard is authorized through actual HTTP', (await owner.request.get(privatePath, { headers: { authorization: 'Bearer dev:admin' } })).status() === 200);
  check('Anonymous dashboard request is denied', (await owner.request.get(privatePath)).status() === 401);
  const other = await owner.request.get(privatePath, { headers: { authorization: 'Bearer dev:visitor' } });
  check('Distinct local non-admin identity cannot read owner dashboard', other.status() === 403 && !('status' in await other.json()));
  await direction.fill('teleport to a fictional planet');
  await page.getByRole('button', { name: 'Send direction', exact: true }).click();
  await page.getByText('Could not understand this direction', { exact: true }).waitFor();
  check('Actual rejected alignment preserves draft', await direction.inputValue() === 'teleport to a fictional planet');
  const ownerCanvas = await page.locator('canvas').elementHandle();
  // VF3: no World/Advanced toggle in the world view; Advanced is the unlisted #advanced address.
  check('World view has no World/Advanced toggle', await page.getByRole('button', { name: 'Advanced', exact: true }).count() === 0);
  await page.evaluate(() => { location.hash = 'advanced'; });
  await page.getByRole('navigation', { name: 'Advanced tools' }).waitFor();
  check('Existing brain and grammar tools retained', await page.getByRole('button', { name: 'brain', exact: true }).isVisible() && await page.getByRole('button', { name: 'grammar', exact: true }).isVisible());
  await page.getByRole('link', { name: '← Back to the world', exact: true }).click();
  await page.getByRole('navigation', { name: 'Advanced tools' }).waitFor({ state: 'detached' });
  check('Advanced transition keeps original viewer mounted', await page.evaluate(el => el === document.querySelector('canvas'), ownerCanvas));
  await page.getByRole('button', { name: 'Your Soul', exact: true }).click();
  check('Advanced preserves refused draft', await direction.inputValue() === 'teleport to a fictional planet');
  await page.getByRole('button', { name: 'Close panel', exact: true }).click();
  await page.getByRole('button', { name: 'Your Soul', exact: true }).click();
  check('Panel close preserves draft', await direction.inputValue() === 'teleport to a fictional planet');
  await page.screenshot({ path: output + '/owner-desktop.png' });
  await page.setViewportSize({ width: 390, height: 844 });
  await direction.waitFor({ state: 'visible' });
  check('Phone has no document horizontal overflow', await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  check('Phone scene remains usable behind collapsible panel', await page.locator('canvas').evaluate(el => el.getBoundingClientRect().height > 250));
  check('Phone submit is visible without scrolling the Soul panel', await page.getByRole('button', { name: 'Send direction', exact: true }).evaluate(el => el.getBoundingClientRect().bottom <= document.querySelector('.human-panel').getBoundingClientRect().bottom));
  const overlap = await page.evaluate(() => { const r = s => { const e = document.querySelector(s); return e && !e.hidden && e.getBoundingClientRect().width ? e.getBoundingClientRect() : null; };
    const hit = (a, b) => a && b && a.right > b.left && a.left < b.right && a.bottom > b.top && a.top < b.bottom;
    const close = r('#soul-panel .panel-close'), hud = r('.world-hud'), status = r('.viewer-status'), bring = r('.bring-agent-open'), chip = r('.viewer-camera-chip'), cam = r('.hud-camera'), tour = r('.eden-tour'), dock = r('.dialogue-dock.closed');
    const top = [status, tour, bring, chip, cam, dock].filter(Boolean);
    return [hit(close, hud), ...top.flatMap((a, i) => top.slice(i + 1).map(b => hit(a, b))), top.some(a => a.bottom > innerHeight / 2 || a.left < 0 || a.right > innerWidth)]; });
  check('Phone: top-bar items (status, Explore, New Soul, Broadcast, camera, conversations) do not overlap, stay in the top half, and the panel close is clear of the bar', overlap.every(x => !x));
  await page.screenshot({ path: output + '/owner-phone.png' });
  writeFileSync(output + '/owner-phone.yml', await page.locator('body').ariaSnapshot());
  await page.getByRole('button', { name: 'Sign out', exact: true }).click();
  await page.locator('#soul-direction').waitFor({ state: 'detached' });
  check('Sign-out clears visible private controls/history/journal', await page.locator('#soul-direction').count() === 0 && await page.locator('.human-panel').getByText('Recent history', { exact: true }).count() === 0 && await page.locator('.human-panel').getByText('Latest journal', { exact: true }).count() === 0);
  check('No uncaught browser errors', errors.length === 0);
  writeFileSync(output + '/summary.json', JSON.stringify({ status: 'pass', checks, errors, scope: 'fresh local fake Eden; no real Privy/cohort/Broadcast qualification' }, null, 2));
  writeFileSync(output + '/index.html', `<title>Game frame proof</title><h1>Local human frame: ${checks.length} checks passed</h1><p>Fake Eden only; no real cohort or Broadcast qualification.</p>${['spectator-desktop','owner-desktop','owner-phone'].map(name => `<h2>${name}</h2><img style="max-width:100%" src="${name}.png">`).join('')}`);
  console.log(JSON.stringify({ output, checks: checks.length, status: 'pass' }));
} catch (error) {
  if (page && !page.isClosed()) { await page.screenshot({ path: output + '/failure.png' }).catch(() => {}); writeFileSync(output + '/failure.yml', await page.locator('body').ariaSnapshot().catch(() => 'unavailable')); }
  writeFileSync(output + '/summary.json', JSON.stringify({ status: 'fail', checks, errors, failure: String(error) }, null, 2));
  console.error(JSON.stringify({ output, status: 'fail', failure: String(error) }));
  process.exitCode = 1;
} finally { await browser.close(); }
