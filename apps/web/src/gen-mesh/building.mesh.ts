import { GENERATORS, type Value } from '@sim/generators';
import { buildingFacadeSlots, type BuildingLayout } from '../../../../packages/generators/src/building.ts';
import { Builder, hashStr, type Finish } from './building-kit.ts';
import { buildingBuffers, beam, col, FACADE, FLOOR0, SLAB, type BuildingJob, type BuildingBuffers } from './building-buffers.ts';
export { buildingBuffers, type BuildingJob, type BuildingBuffers } from './building-buffers.ts';
import { groundRealismFor } from './ground-palette.ts';
import { registerMesh, type MeshCtx } from './registry.ts';
import { decalGroups } from './faces.ts'; // XP8 hook
// Z2: { def hash: the def hash its random facade details are drawn from }. A size-range or plan-footprint edit to a
// library building changes its hash but not its look, so the edited def keeps the facade of the revision it replaced
// (generated by team/scratch/t4/z2/looks/mk-looks.mts against main 23a665f48). Keyed by the new hash, so a world's
// pinned older revision keeps drawing from its own hash; the 40-building pin in building-authoring.test.ts guards it.
import buildingLooks from './building-looks.json' with { type: 'json' };

const templates = new Map<string, THREE.Group>();
const ORNAMENTS = new Set(['chimney', 'shutters', 'flowerBoxes', 'quoins', 'hood', 'doorLamp']);

registerMesh({
  gen: 'building/1',
  build(ctx) {
    const gen = GENERATORS['building/1'] as unknown as { layout(p: Record<string, unknown>, a: Record<string, unknown>): BuildingLayout };
    const L = gen.layout(ctx.params as Record<string, unknown>, ctx.args);
    const paint = paintOf(ctx), key = templateKey(ctx, paint);
    let tpl = templates.get(key);
    if (!tpl) {
      // New switch defaults must not reshuffle the legacy random facade details; nor may decals (XP8 hook: a sign edit
      // must leave the shutters, flower boxes and chimney where they were).
      // lane W1: the geometry may already have been made in a worker (prefetchBuilding, at the world's first build)
      const job = buildingJob(ctx, L, paint), mat = L.material in FACADE ? L.material : 'plaster';
      // W2b: old Eden's per-building finish; Eden's own look (the meadow ground) varies painted render
      const finish = buildingFinish(mat, paint, col(ctx.params.roofColor, '#8a3b2a'), job.seed, groundRealismFor((ctx.model.state as { ground?: { palette?: string } }).ground?.palette));
      const built = emitBuilding(L, takeBuilt(key) ?? buildingBuffers(job), ctx.materials, finish);
      tpl = built.group;
      for (const group of decalGroups(ctx.params.decals, ctx.baked?.slots, L.yaw)) tpl.children[0].add(group); // XP8 hook: wall decals
      tpl.userData.tris = built!.tris;
      if (templates.size > 64) { for (const g of templates.values()) disposeGroup(g); templates.clear(); }
      templates.set(key, tpl);
    }
    const g = tpl.clone(true);
    g.userData = { ...tpl.userData };
    attachInteriorView(g, L);
    return g;
  },
  // no instanceKey: the interior view hides storeys per building per frame, which instancing would lose;
  // the geometry is still shared (one template per def/params/paint, cloned).
});

// ---------------------------------------------------------------- lane W1: building geometry in workers
// A world's first build hands every building to building.worker.ts (two workers) before it starts, so the ~0.3 s of
// facade geometry (0.6 s at 2x CPU) is made beside the main thread's terrain and other things; build() then takes the
// finished soups (takeBuilt). Same code, same data, same floats. No Worker (tests), a failed worker or
// `?buildingWorker=0`: built in place, as before.
const made = new Map<string, BuildingBuffers>(), waiting = new Map<string, Promise<void>>();
let workers: Worker[] | null | undefined, nextJob = 0;
const replies = new Map<number, (m: BuildingBuffers | null) => void>();
function buildingWorkers(): Worker[] | null {
  if (workers !== undefined) return workers;
  try {
    const off = typeof location !== 'undefined' && new URLSearchParams(location.search).get('buildingWorker') === '0';
    workers = off || typeof Worker === 'undefined' ? null : [0, 1].map(() => new Worker(new URL('./building.worker.ts', import.meta.url), { type: 'module' }));
  } catch { workers = null; }
  for (const w of workers ?? []) {
    w.onmessage = (ev: MessageEvent<{ id: number; out: BuildingBuffers | null }>) => { const f = replies.get(ev.data.id); replies.delete(ev.data.id); f?.(ev.data.out); };
    w.onerror = () => { for (const f of replies.values()) f(null); replies.clear(); for (const x of workers ?? []) x.terminate(); workers = null; };
  }
  return workers;
}
function takeBuilt(key: string): BuildingBuffers | null { const m = made.get(key) ?? null; if (m) made.delete(key); return m; }
/** Start this building's geometry in a worker; the promise settles when build() can take it (or must make it itself).
 *  null: nothing to wait for (already built, not a worker page, or the same building is already on its way). */
export function prefetchBuilding(ctx: Pick<MeshCtx, 'def' | 'entity' | 'params' | 'args'>): Promise<void> | null {
  const ws = buildingWorkers(); if (!ws) return null;
  const gen = GENERATORS['building/1'] as unknown as { layout(p: Record<string, unknown>, a: Record<string, unknown>): BuildingLayout };
  const L = gen.layout(ctx.params as Record<string, unknown>, ctx.args), paint = paintOf(ctx), key = templateKey(ctx, paint);
  if (templates.has(key) || made.has(key)) return null;
  const pending = waiting.get(key); if (pending) return pending;
  const id = ++nextJob, job = buildingJob(ctx, L, paint);
  const p = new Promise<void>((done) => {
    replies.set(id, (out) => { if (out) made.set(key, out); waiting.delete(key); done(); });
    try { ws[id % ws.length].postMessage({ id, job }); } catch { replies.delete(id); waiting.delete(key); done(); }
  });
  waiting.set(key, p);
  return p;
}
/** Drop geometry that was made but never taken (a world's first build is over). */
export function clearBuildingPrefetch() { made.clear(); }
// state.paint repaints the walls; while it still holds the def's default, the `wall` param decides
function paintOf(ctx: Pick<MeshCtx, 'def' | 'entity' | 'params'>): string {
  const paintDefault = (ctx.def.state?.paint as { default?: string } | undefined)?.default;
  const painted = ctx.entity.state?.paint !== undefined && ctx.entity.state.paint !== paintDefault;
  return painted ? col(ctx.entity.state!.paint, '#f1e7d2') : col(ctx.params.wall, col(paintDefault, '#f1e7d2'));
}
const templateKey = (ctx: Pick<MeshCtx, 'def' | 'params' | 'args'>, paint: string) => `${ctx.def.hash}|${JSON.stringify(ctx.params)}|${paint}|${JSON.stringify(ctx.args)}`;

function disposeGroup(g: THREE.Object3D) { g.traverse((o) => { const m = o as THREE.Mesh; if (m.isMesh) m.geometry.dispose(); }); }

// ---------------------------------------------------------------- the drawing

/** W2b: old Eden's per-building finish. The facade material decides the wall (brick: running or Flemish bond; stone:
 *  ashlar; wood: clapboard; plaster: limewash); in Eden's own look (the meadow ground) painted render varies as old
 *  Eden's districts did: some brick, dressed stone or clapboard. The roof colour picks clay tile, slate or shingle.
 *  Glass and metal buildings keep the plain kit. */
export function buildingFinish(mat: string, paint: string, roofCol: string, seed: number, eden: boolean): Finish | null {
  if (mat === 'glass' || mat === 'metal') return null;
  const pick = (Math.imul(seed ^ 0x9e3779b9, 2654435761) >>> 0) / 4294967296;
  const hsl = { h: 0, s: 0, l: 0 }, hueOf = (c: string) => { new THREE.Color(c).getHSL(hsl, THREE.SRGBColorSpace); return hsl.h * 360; };
  let wall = mat === 'brick' ? (pick < 0.65 ? 0 : 1) : mat === 'stone' ? 2 : mat === 'wood' ? 3 : 4;
  if (mat === 'plaster' && eden) {
    // earthy paints read as brick or stone; pastels as clapboard or limewash; whites as clapboard or limewash
    const hue = hueOf(paint), warm = (hue < 50 || hue > 340) && hsl.l < 0.72 && hsl.s > 0.18;
    wall = warm ? (pick < 0.45 ? 0 : pick < 0.6 ? 1 : pick < 0.75 ? 2 : 4) : hsl.l > 0.82 ? (pick < 0.5 ? 3 : 4) : pick < 0.45 ? 3 : pick < 0.6 ? 2 : 4;
  }
  const hue = hueOf(roofCol), roof = hsl.s < 0.22 || hsl.l < 0.2 ? 1 : hue < 40 || hue > 330 ? 0 : 2;
  return { wall, roof };
}

export function buildingJob(ctx: Pick<MeshCtx, 'def' | 'params' | 'args'>, L: BuildingLayout, paint: string): BuildingJob {
  // New switch defaults must not reshuffle the legacy random facade details; nor may decals (XP8 hook: a sign edit
  // must leave the shutters, flower boxes and chimney where they were).
  const legacyParams = Object.fromEntries(Object.entries(ctx.params).filter(([k]) => !ORNAMENTS.has(k) && k !== 'decals'));
  // Nor may an authored plan's footprint annotation (plan.size: rooms resize with the building) or its landing strip
  // (plan.landing: two facing flights narrow, lane BSGEN 2026-10-21).
  const plan = legacyParams.plan as Record<string, unknown> | undefined;
  if (plan && typeof plan === 'object' && ('size' in plan || 'landing' in plan)) { const { size: _size, landing: _landing, ...rest } = plan; legacyParams.plan = rest as Value; }
  const look = (buildingLooks as Record<string, string>)[ctx.def.hash] ?? ctx.def.hash;
  const seed = hashStr(`${look}|${JSON.stringify(legacyParams)}|${paint}|${JSON.stringify(ctx.args)}`);
  // Keep the library's original sill palette at its preset trim (drawBuilding)
  const presetTrim = (ctx.def.params.trim as { default?: unknown } | undefined)?.default ?? '#6b4a2b';
  return { L, params: ctx.params as Record<string, Value>, presetTrim, paint, seed };
}
function emitBuilding(L: BuildingLayout, made: BuildingBuffers, materials: MeshCtx['materials'], finish: Finish | null): { group: THREE.Group; tris: number } {
  const b = Builder.fromRaw(made.raw); b.finish = finish; // W2b: the building's surface finish (materials only)
  const { groups, tris } = b.emit(materials);
  const root = new THREE.Group(); root.name = 'building';
  const inner = new THREE.Group(); inner.name = 'building-canonical'; inner.rotation.y = L.yaw;
  if (made.anchors.length) inner.userData.edenSmokeSources = made.anchors.map((p) => [...p, 1.4]); // W2: atmosphere smoke
  for (const g of groups.values()) inner.add(g);
  root.add(inner);
  return { group: root, tris };
}

// ---------------------------------------------------------------- interior view

const query = typeof location !== 'undefined' ? new URLSearchParams(location.search) : new URLSearchParams();
const HIDE_ROOFS = query.has('hideRoofs') && query.get('hideRoofs') !== '0';
const CUT = query.has('cut') ? Number(query.get('cut')) : null;
const camLocal = new THREE.Vector3(), inv = new THREE.Matrix4();
let mainCamera: THREE.Camera | null = null;

/** Hide the roof and the storeys above the camera when it is inside the footprint (or always, with ?hideRoofs=1). */
function attachInteriorView(root: THREE.Object3D, L: BuildingLayout) {
  const inner = root.children[0];
  if (!inner) return;
  const halfX = (L.round ? L.round.R : L.W / 2) + 0.4, halfZ = (L.round ? L.round.R : L.D / 2) + 0.4 + (L.porch?.depth ?? 0);
  let hideAbove = Infinity, hideRoof = false, keepSlab = -1;
  const decide = (camera: THREE.Camera) => {
    const live = (globalThis as { __buildingView?: { hideRoofs?: boolean; cut?: number | null } }).__buildingView;
    const roofsOff = live?.hideRoofs ?? HIDE_ROOFS, cut = live?.cut !== undefined ? live.cut : CUT;
    hideRoof = roofsOff; hideAbove = cut !== null && cut !== undefined && roofsOff ? cut : Infinity; keepSlab = -1;
    inv.copy(inner.matrixWorld).invert(); camLocal.setFromMatrixPosition(camera.matrixWorld).applyMatrix4(inv);
    if (Math.abs(camLocal.x) < halfX && Math.abs(camLocal.z) < halfZ && camLocal.y < L.wallTop + L.roofRise && camLocal.y > -1) {
      hideRoof = true;
      const level = Math.max(0, Math.floor((camLocal.y - FLOOR0 + 0.3) / L.fh));
      hideAbove = Math.min(hideAbove, level);
      // the camera's own ceiling stays while the camera is below it (an eye-level view keeps its ceiling)
      if (!roofsOff && camLocal.y < (level + 1) * L.fh + FLOOR0 - SLAB - 0.05) keepSlab = level + 1;
    }
  };
  // XP8 hook: one decision per building per rendered frame and camera, however many meshes (decals add up to 16) ask.
  let decided = -1, decidedFor: THREE.Camera | null = null;
  const decideOnce = (renderer: THREE.WebGLRenderer, camera: THREE.Camera) => {
    const frame = renderer?.info?.render?.frame;
    if (frame === undefined || frame !== decided || camera !== decidedFor) { decided = frame ?? -1; decidedFor = camera; decide(camera); }
  };
  // furniture and other children on hidden storeys follow the cut (WorldEntityLayer reads this; L1 patch 04)
  const floorOf: Record<string, number> = { ground: 0, porch: 0, roof: L.floors, ...(L.balcony ? { balcony: L.balcony.floor } : {}) };
  for (let k = 1; k < L.floors; k++) floorOf[`floor-${k}`] = k;
  for (const r of L.rooms) floorOf[r.id] = r.floor;
  for (const s of buildingFacadeSlots(L, Object.keys(floorOf))) if (s.floor !== undefined) floorOf[s.id] = s.floor;
  root.userData.interior = { cut: () => hideAbove, floorOf };
  inner.traverse((o) => {
    const mesh = o as THREE.Mesh; if (!mesh.isMesh) return;
    const gname = mesh.parent?.name ?? '';
    const slab = gname.startsWith('slab-'), level = gname === 'roof' ? Infinity : Number(gname.replace(/^(level|slab)-/, ''));
    const hidden = () => (level === Infinity ? hideRoof : slab ? level !== keepSlab && (level > hideAbove || (level === L.floors && hideRoof)) : level > hideAbove);
    mesh.onBeforeRender = (renderer, _s, camera, geometry) => {
      mainCamera = camera; decideOnce(renderer, camera);
      (geometry as THREE.BufferGeometry).setDrawRange(0, hidden() ? 0 : Infinity);
    };
    mesh.onBeforeShadow = (renderer, _o, _c, _sc, geometry) => {
      if (mainCamera) decideOnce(renderer, mainCamera);
      (geometry as THREE.BufferGeometry).setDrawRange(0, hidden() ? 0 : Infinity);
    };
    mesh.onAfterRender = (_r, _s, _c, geometry) => { (geometry as THREE.BufferGeometry).setDrawRange(0, Infinity); };
    mesh.onAfterShadow = (_r, _o, _c, _sc, geometry) => { (geometry as THREE.BufferGeometry).setDrawRange(0, Infinity); };
  });
}
